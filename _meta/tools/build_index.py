#!/usr/bin/env python3
"""Regenerate INDEX.md: a navigable map of the Knowledge vault.

Walks technical/, softskills/ and work/ and lists every subject with its
standard sub-folders (concepts, docs, courses, projects, examples, ...).
Inside courses/projects/examples it lists only the top-level entries, so
huge repos don't flood the index. Run from anywhere:
    python _meta/tools/build_index.py
"""
import os, datetime, pathlib

VAULT = pathlib.Path(__file__).resolve().parents[2]
ROOTS = ["technical", "softskills"]  # work/ is deliberately left out: INDEX.md is in git
CONTAINERS = {"courses", "projects", "examples", "datasets", "media", "docs",
              "notes", "snippets", "concepts", "labs"}
SKIP = {".git", "node_modules", ".venv", "__pycache__", ".idea", ".gitkeep"}
ICON = {"concepts": "notes", "notes": "notes", "docs": "docs", "courses": "course",
        "projects": "project", "examples": "example", "datasets": "data",
        "media": "media", "snippets": "snippet", "labs": "lab"}

def ls(p):
    try:
        return sorted([e for e in os.scandir(p) if e.name not in SKIP],
                      key=lambda e: (not e.is_dir(), e.name.lower()))
    except FileNotFoundError:
        return []

def rel(p):
    return pathlib.Path(p).relative_to(VAULT).as_posix()

def link(p, text=None):
    r = rel(p)
    return f"[{text or os.path.basename(p)}](<{r}>)"

def subject_block(path, depth, out):
    """path is a subject folder (contains container folders or files)."""
    entries = ls(path)
    containers = [e for e in entries if e.is_dir() and e.name in CONTAINERS]
    others = [e for e in entries if not (e.is_dir() and e.name in CONTAINERS)]
    for c in containers:
        kids = ls(c.path)
        names = ", ".join(link(k.path, k.name + ("/" if k.is_dir() else "")) for k in kids[:40])
        more = f" … +{len(kids)-40}" if len(kids) > 40 else ""
        out.append(f"{'  '*depth}- **{c.name}/** ({len(kids)}): {names}{more}")
    for e in others:
        if e.is_dir():
            out.append(f"{'  '*depth}- {link(e.path, e.name + '/')}")
            subject_block(e.path, depth + 1, out)
        elif e.name.endswith((".md", ".txt", ".tsv")):
            out.append(f"{'  '*depth}- {link(e.path)}")

def main():
    out = ["# Vault index", "",
           f"_Auto-generated by `_meta/tools/build_index.py` on {datetime.date.today()}. Do not edit by hand._", "",
           "Legend: **concepts/notes** = your notes · **docs** = PDFs/slides/cheat-sheets · "
           "**courses** = third-party course material · **projects** = your builds · "
           "**examples** = demos & samples · **datasets** · **media** · **snippets**", ""]
    for root in ROOTS:
        rp = VAULT / root
        if not rp.exists():
            continue
        out += [f"## {root}/", ""]
        for dom in ls(rp):
            if not dom.is_dir():
                continue
            out.append(f"### {root}/{dom.name}")
            for subj in ls(dom.path):
                if subj.is_dir():
                    out.append(f"- {link(subj.path, subj.name + '/')}")
                    subject_block(subj.path, 1, out)
                else:
                    out.append(f"- {link(subj.path)}")
            out.append("")
    (VAULT / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", VAULT / "INDEX.md")

if __name__ == "__main__":
    main()
